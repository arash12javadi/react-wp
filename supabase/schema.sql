create table if not exists public.pages (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text unique not null,
  content text default '',
  excerpt text default '',
  status varchar(20) default 'draft' check (status in ('draft', 'published')),
  is_post boolean not null default false,
  category_id uuid references public.categories(id) on delete set null,
  featured_category_id uuid references public.categories(id) on delete set null,
  posts_limit integer not null default 6 check (posts_limit > 0),
  display_layout varchar(20) not null default 'grid' check (display_layout in ('grid', 'list')),
  layout varchar(20) not null default 'boxed' check (layout in ('boxed', 'wide', 'full')),
  show_sidebar boolean not null default false,
  seo_title text,
  meta_description text,
  focus_keyword text,
  canonical_url text,
  noindex boolean not null default false,
  og_title text,
  og_description text,
  og_image text,
  twitter_card varchar(30) not null default 'summary_large_image',
  comments_open boolean not null default true,
  author_id uuid references auth.users(id) on delete set null,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  page_id bigint references public.pages(id) on delete cascade,
  parent_id bigint references public.comments(id) on delete cascade,
  -- References profiles, not auth.users, so PostgREST can embed the author in one request.
  author_id uuid references public.profiles(id) on delete cascade,
  author_name text,
  author_email text,
  content text not null,
  status varchar(20) default 'pending',
  created_at timestamptz default timezone('utc'::text, now()) not null
);

create index if not exists comments_page_id_idx on public.comments(page_id);
create index if not exists comments_parent_id_idx on public.comments(parent_id);

create table if not exists public.options (
