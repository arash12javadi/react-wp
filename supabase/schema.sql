create table if not exists public.plugins (
  plugin_id text primary key,
  name text not null,
  version text not null,
  author text,
  description text default '',
  folder text,
  source text not null default 'bundled',
  active boolean not null default false,
  installed_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

create table if not exists public.media (
  id uuid primary key default gen_random_uuid(),
  title varchar(255),
  alt_text text,
  url text not null,
  provider varchar(50) not null default 'external'
    check (provider in ('cloudinary', 'imagekit', 'external')),
  file_name varchar(255),
  -- Cloudinary public_id / ImageKit fileId. Deleting the asset at the provider needs this.
  provider_file_id text,
  width integer,
  height integer,
  bytes bigint,
  mime_type varchar(100),
