/**
 * Universal core schema, one dialect per backend.
 *
 * These are the tables the whole CMS needs to boot in any backend: the content model (pages,
 * posts, categories, menus, comments, media), the options key-value store, the plugin registry,
 * the singleton theme row (`theme_settings`), the translations catalogue (`rwp_translations`),
 * the optional per-person details (`profile_details`), the saved-items store (`bookmarks`), and
 * `rwp_users` for the universal auth engine. The Supabase backend keeps using the full
 * `supabase/schema.sql` (23 tables plus RLS policies, triggers and RPCs); these files are the
 * platform-agnostic equivalent that provisioning can run identically on PostgreSQL, MySQL and
 * SQLite.
 *
 * Every script is idempotent (`create table if not exists` / `create index if not exists`), so it
 * can be re-run against an existing database to add whatever it is missing without losing data.
 */
