/** Returns the idempotent core schema for a backend, or the full Supabase schema for Supabase. */
export function schemaFor(dbType: DbType): string {
  switch (dbType) {
    case 'postgres':
      return pgSchema;
    case 'mysql':
      return mysqlSchema;
    case 'sqlite':
    case 'libsql':
      return sqliteSchema;
    case 'supabase':
      // The Supabase backend provisions through supabase/schema.sql (RLS + RPCs + triggers) via the
      // direct database connection, not through this platform-agnostic subset.
      return '';
    default:
      return pgSchema;
  }
}

